<tbody><tr><td class="storytitle">Edward Said On Moral Responsibility</td></tr>
<tr><td height="1" class="storyunderline" style="font-size: 0;"><img src="/sites/palestinechronicle.com/images/speck.gif" width="1" height="1"></td></tr>
<tr><td class="storybyline">Wednesday, October 31 2001 @ 05:41 PM GMT</td></tr><tr><td>
<br>
By Dana Charkasi 
<br>

<br>
Vienna - Governments and intellectuals have to bear moral responsibility and act accordingly, especially in the Israeli-Palestinian conflict, said Palestinian-American professor of comparative literature, Edward Said, speaking in Vienna last week. <br><br>Said, a renowned intellectual and advocate of the Palestinian cause, was speaking at the joint invitation of the Austrian Institute for International Affairs and the Austrian Academy of Diplomacy. 
<br>

<br>
"To say -- as is often the case with liberal intellectuals -- that both sides are right and wrong or that there are merits to each case [avoids the issue] and is also moral cowardliness." Said was referring to the existing asymmetry in the Palestinian-Israeli conflict such as the ongoing occupation of Palestinian lands, as well as the vast gap in the power equation between Israel's modern army and a "relatively defenceless" Palestinian people. 
<br>

<br>
"[The Palestinians] have suffered far more at Israel's hands than any Israelis have at their hands; there is simply no comparison." Most important, Said believes, is that governments take moral responsibility, hinting at unconditional American financial and ideological support of Israel. 
<br>

<br>
"The plain truth of the matter is that anti-Americanism is tied directly to the US behaviour of lecturing the world on democracy and justice while openly supporting the exact opposite." A moral stand is also required from Arab governments to provide their countries with better living conditions and also to do away with simplified and one-sided ideologies prevailing in them, a condition hampering development and reconciliation in the Middle East. 
<br>

<br>
"The governments are either incapable or unwilling to stop the rise of Islamic extremism, [or protect] the brave secularists who protest human rights abuses, fight clerical tyranny and try to speak and act on behalf of a new modern Arab democratic order. 
<br>

<br>
They are pretty much left alone in their fight, unassisted by the official culture." The real culprit, according to Said, is a system of education with "woefully unequipped teachers and a near total inability to think critically..." While the Arab world tends to deny or diminish the traumatic Holocaust experience of the Jewish people and neglect its relevance in the Arab-Israeli conflict, Israelis on the other hand deny the suffering of the Palestinian people and refuse to take responsibility for the injustice done to them by Israel. 
<br>

<br>
"How has it come to be morally possible and justifiable for Israel to maintain and defend a 35-year-old occupation? Even Israeli peace advocates remain fixated on the supposed absence of a Palestinian peace camp, forgetting that a people under occupation doesn't have the same luxury as the occupier to decide whether an interlocutor exists." Said also denounced stubborn patterns prevailing among Arab intellectuals. 
<br>

<br>
"We have refused interaction and debate (with Israel), disparaging and calling [such activity] 'normalisation' or 'collaboration'. Refusing to compromise and put forward a just position cannot possibly be construed as a concession," he said. 
<br>

<br>
There is also the question of moral responsibility of Western journalists reporting on the Palestinian-Israeli conflict. "The media always speaks of 'Palestinian violence;' there is no mention of the fact that the Israeli army has been involved in a military occupation of Palestinian land since 1967. And there is also no mention of the fact that an occupied people has the right to resistance by every known international protocol, treaty and charter," said Said. 
<br>

<br>
For Said, the answer to the Palestinians' need is "in resistance, well-organised civil disobedience against military occupation and illegal settlements and an educational programme that promotes coexistence, citizenship and the worth of human life." 
<br>

